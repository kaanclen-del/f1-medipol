-- F1 Social: yönetilebilir sosyal bağlantılar
create table if not exists public.site_social_links (
  id bigint generated by default as identity primary key,
  label text not null check (char_length(label) between 1 and 40),
  url text not null check (char_length(url) <= 500),
  icon text not null default 'link' check (icon in ('instagram', 'linkedin', 'tiktok', 'whatsapp', 'link')),
  sort_order integer not null default 0,
  is_visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.site_social_links enable row level security;

-- Herkese açık okuma yalnızca görünür bağlantılar içindir.
drop policy if exists "Public can read visible social links" on public.site_social_links;
create policy "Public can read visible social links"
on public.site_social_links for select
using (is_visible = true);

-- Yönetim işlemleri service-role kullanan, ayrıca admin kontrolü yapan API üzerinden yürütülür.
revoke all on public.site_social_links from anon, authenticated;
grant select on public.site_social_links to anon, authenticated;

insert into public.site_social_links (label, url, icon, sort_order, is_visible)
select 'Instagram', 'https://www.instagram.com/f1social/', 'instagram', 0, true
where not exists (
  select 1 from public.site_social_links where icon = 'instagram'
);
